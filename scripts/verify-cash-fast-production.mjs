import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
const base = "https://www.adocebrigaderia.com.br";
const response = await fetch(`${base}/operacao`);
if(response.status !== 200) throw Error("Operação indisponível no domínio oficial");
const html = await response.text();
const entry = html.match(/src="(\/assets\/[^"\s]+\.js)"/)?.[1];
if(!entry) throw Error("Entrada do site ausente");
const js = await (await fetch(base+entry)).text();
const access = js.match(/assets\/(AccessApp-[^"'`\s]+\.js)/)?.[0];
if(!access) throw Error("Pacote operacional ausente");
const accessCode = await (await fetch(`${base}/${access}`)).text();
const cashAsset = accessCode.match(/OperationCommercialAdmin-[^"'`\s]+\.js/)?.[0];
if(!cashAsset) throw Error("Pacote do caixa ausente");
const cashCode = await (await fetch(`${base}/assets/${cashAsset}`)).text();
const features = ["Como será o pagamento?","Pagar com duas ou mais formas","Tentar finalizar novamente","Reimprimir vendas de hoje","Troco previsto","Valor recebido"];
const missing = features.filter(text=>!cashCode.includes(text));
if(missing.length) throw Error(`Recursos ausentes: ${missing.join(", ")}`);
const hash = text=>createHash("sha256").update(text).digest("hex");
const localHash = hash(readFileSync(`dist/assets/${cashAsset}`,"utf8"));
const remoteHash = hash(cashCode);
if(localHash!==remoteHash) throw Error("Pacote do domínio diverge do build validado");
const result = {url:`${base}/operacao`,status:response.status,entry,access,cashAsset,features,identicalToValidatedBuild:true,sha256:remoteHash,validationScope:"Disponibilidade e pacote publicado; fluxo interativo validado localmente com API simulada"};
writeFileSync("entregas/producao-caixa-rapido-20261008.json",JSON.stringify(result,null,2));
console.log(result);
